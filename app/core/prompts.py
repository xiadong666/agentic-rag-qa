"""提示词（Prompt）设计。

本文件集中管理所有提示词 —— 提示词是“配置”不是“散落的字符串”，
集中后好维护、好做 A/B、也便于向同事解释。

设计要点（写 RAG 系统提示词的通用套路）：
1. 明确“身份 + 任务 + 约束”。
2. 约束里写死三条铁律：只依据资料回答 / 引用要带编号 / 不知道就说不知道。
   （“编造”是 RAG 最大的风险源，提示词约束是第一道闸门。）
3. 给“引用格式”示例（few-shot 一小段），比只说“请引用”效果好得多。
"""
