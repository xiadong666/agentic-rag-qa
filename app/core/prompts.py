def format_history_block(history_text: str | None) -> str:
    """把历史渲染成系统提示里的一段。没有历史时给占位说明。"""
    if not history_text:
        return "对话历史：（无，这是本轮会话的第一问）"
    return "对话历史（仅用于理解用户指代，回答仍以最新资料为准）：\n" + history_text


def format_context_block(chunks) -> str:
    """把检索到的资料渲染成带编号的文本块。

    chunks: 每个元素需具备 text / doc_title / page 属性。
    """
    lines: list[str] = []
    for i, c in enumerate(chunks, start=1):
        page = f"，第 {c.page} 页" if getattr(c, "page", None) else ""
        lines.append(f"[{i}] 来源《{c.doc_title}》{page}：{c.text}")
    return "\n\n".join(lines)


